#!/usr/bin/env python3
"""Regenerate BENCHMARKS.md's generated parts from results/results.json.

Why this exists: step 2 of the publish order used to be "update BENCHMARKS.md by hand",
and on 2026-08-05 that left **six per-row tables, the header date and the brood commit**
carrying the previous run's figures while the prose around them described the new one.
A number a human retypes per publish is a number that goes stale. So everything
mechanically derivable from `results.json` is generated here, and the prose — which is
the part worth writing by hand — is left alone.

    python3 bench/tables.py           # rewrite in place
    python3 bench/tables.py --check   # exit 1 if anything would change (CI / pre-publish)

What it owns:
  * the machine/date/versions line, from `_meta`;
  * the **Overall** rating block (between the OVERALL markers);
  * every ordered per-row table: the times, `Brood rank`, and the `vs best` column.
    A table is recognised by its `| benchmark | … | Brood rank |` header, and its
    language columns are read from that header, so re-ordering or dropping a column in
    the markdown is honoured rather than overwritten.

What it does not own: the codec table (`json`/`regex`/`base64`) keeps no `vs best` — see
that table's own note — and every paragraph of analysis. If you change a *number* in
prose you are on your own; if you change one in a table, run this instead.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results" / "results.json"
DOC = ROOT / "BENCHMARKS.md"

# The rows the positioning chart's aggregate uses — kept identical to `chart.py`'s
# COMPUTE so the header rating and the chart cannot disagree.
COMPUTE = ["fib", "loop", "reduce", "primes", "collatz", "mandelbrot",
           "matmul", "strings", "wordcount", "bintree", "sort"]

LANG_COL = {".NET": "dotnet", "Elixir": "elixir", "Node": "node", "Brood": "brood",
            "Ruby": "ruby", "Python": "python", "Clojure": "clojure"}
PRETTY = {v: k for k, v in LANG_COL.items()}

OVERALL_BEGIN = "<!-- BEGIN OVERALL (generated by bench/tables.py) -->"
OVERALL_END = "<!-- END OVERALL -->"
MACHINE_BEGIN = "<!-- BEGIN MACHINE (generated by bench/tables.py) -->"
MACHINE_END = "<!-- END MACHINE -->"


def load():
    res = json.load(open(RESULTS))
    starts = {l: d.get("wall_ms") for l, d in res["startup"]["langs"].items()}
    return res, starts


def compute(res, starts, row, lang):
    """`wall - startup` in ms, or None when that language has no port / no sample."""
    d = res.get(row, {}).get("langs", {}).get(lang)
    if not d or d.get("wall_ms") is None:
        return None
    if row == "startup":
        return d["wall_ms"]
    return max(0.0, d["wall_ms"] - starts.get(lang, 0))


def fmt_ms(v):
    if v is None:
        return "—"
    if v < 1:
        return "&lt;1ms"           # a cell at the startup-subtraction floor
    return f"{round(v)}ms" if v < 1000 else f"{v / 1000:.1f}s"


def rating(brood, best):
    """The `vs best` cell: how far Brood is from the fastest column in that table."""
    if brood is None or best is None or best <= 0:
        return "—"
    return "**best**" if brood <= best else f"{brood / best:.1f}×"


def langs_of_header(header):
    out = []
    for cell in [c.strip() for c in header.strip().strip("|").split("|")][1:]:
        name = re.sub(r"<sup>.*?</sup>", "", cell).strip()
        if name in LANG_COL:
            out.append((name, LANG_COL[name]))
    return out


def machine_line(res):
    m = res["_meta"]
    v = m["versions"]
    date = m["date"].split(" ")[0]
    brood = v["brood"].replace("brood ", "")
    commit = m.get("brood_commit")
    brood = f"{brood} (`{commit}`)" if commit else brood
    elixir = re.sub(r" \(compiled with Erlang/OTP (\d+)\)", r" / OTP \1", v["elixir"])
    elixir = elixir.replace("Elixir ", "").replace(" (", " (")
    return (
        f"Machine: `{m['host']}`, {m['cores']}-core x86-64, "
        f"Linux {m['platform'].split('-')[1]}, **{date}** · Brood {brood} · "
        f"{v['clojure']} · Elixir {elixir} · {v['python']} · Node {v['node']} · "
        f"Ruby {v['ruby'].split(' (')[0].replace('ruby ', '')} · .NET {v['dotnet']}."
    )


def overall_block(res, starts):
    """Brood's standing in one place: the aggregate, the typical row, and the spread.

    Three ratios, because each answers a different question and any one alone misleads:
    the **sum** is what the positioning chart plots and is dominated by the largest rows
    (`matmul` alone is ~a third of Brood's total), the **geometric mean** is the typical
    row, and the **median** is the typical row with the outliers' pull removed. Publishing
    only the sum would flatter or damn Brood depending on which way its worst row moved,
    so all three ship together with the distribution beneath them.
    """
    langs = [l for l in res["startup"]["langs"] if all(
        compute(res, starts, r, l) is not None for r in COMPUTE)]
    sums = {l: sum(compute(res, starts, r, l) for r in COMPUTE) for l in langs}
    best_sum = min(sums.values())
    order = sorted(sums, key=lambda l: sums[l])
    agg = sums["brood"] / best_sum
    rank = order.index("brood") + 1

    # Per-row distance to that row's best, over the like-for-like rows.
    ratios = []
    for r in COMPUTE:
        vals = [compute(res, starts, r, l) for l in langs]
        vals = [v for v in vals if v is not None]
        b = compute(res, starts, r, "brood")
        if b and vals and min(vals) > 0:
            ratios.append(b / min(vals))
    geo = 1.0
    for x in ratios:
        geo *= x
    geo **= 1 / len(ratios)
    med = sorted(ratios)[len(ratios) // 2]
    wins = sum(1 for x in ratios if x <= 1.0)
    close = sum(1 for x in ratios if 1.0 < x <= 2.0)
    mid = sum(1 for x in ratios if 2.0 < x <= 5.0)
    far = sum(1 for x in ratios if x > 5.0)
    worst_row = COMPUTE[max(range(len(ratios)), key=lambda i: ratios[i])]
    worst = max(ratios)

    others = " · ".join(
        f"{PRETTY[l]} {sums[l] / best_sum:.1f}×" for l in order if l != "brood")
    return [
        OVERALL_BEGIN,
        "### Overall rating",
        "",
        f"| | Brood | of {len(langs)} |",
        "|---|---|---|",
        f"| **aggregate compute vs best** (Σ over the {len(ratios)} like-for-like rows) "
        f"| **{agg:.1f}×** | rank {rank} |",
        f"| **typical row vs best** (geometric mean) | **{geo:.1f}×** | — |",
        f"| median row vs best | **{med:.1f}×** | — |",
        f"| rows at or ahead of the field's best | **{wins}** | — |",
        f"| rows within 2× of best | **{wins + close}** | — |",
        f"| rows 2–5× off | {mid} | — |",
        f"| rows more than 5× off | {far} | worst: `{worst_row}` {worst:.0f}× |",
        "",
        f"The field on the same aggregate: {others}.",
        "",
        "**Read all three.** The aggregate is a *sum*, so it is dominated by the largest "
        "rows — one row can carry it. The geometric mean is the typical row, and the median "
        "is the typical row with the outliers' pull removed: today they read "
        f"{agg:.1f}× / {geo:.1f}× / {med:.1f}×, and that spread *is* the finding — most rows "
        "are close and a few are far. The distribution underneath is there so no single "
        "number can hide it.",
        OVERALL_END,
    ]


def regenerate(text, res, starts):
    lines = text.split("\n")
    out, i = [], 0
    tables = rows = 0
    while i < len(lines):
        ln = lines[i]

        if ln.startswith(MACHINE_BEGIN):
            out += [MACHINE_BEGIN, machine_line(res)]
            while i < len(lines) and not lines[i].startswith(MACHINE_END):
                i += 1
            out.append(MACHINE_END)
            i += 1
            continue

        if ln.startswith(OVERALL_BEGIN):
            out += overall_block(res, starts)
            while i < len(lines) and not lines[i].startswith(OVERALL_END):
                i += 1
            i += 1
            continue

        if ln.startswith("| benchmark |") and "Brood rank" in ln:
            cols = langs_of_header(ln)
            body_start = i + 2
            is_codec = body_start < len(lines) and lines[body_start].startswith("| `json`")
            rated = "vs best" in ln or not is_codec
            header = ln if ("vs best" in ln or is_codec) else ln.replace(
                "| Brood rank |", "| Brood rank | vs best |")
            out.append(header)
            i += 1
            sep = "|---" * (len(cols) + 2 + (1 if rated and not is_codec else 0)) + "|"
            out.append(sep)
            i += 1
            tables += 1
            while i < len(lines) and lines[i].startswith("|"):
                m = re.match(r"\| `([a-z0-9-]+)`( <sup>[a-z]</sup>)?( \(wall\))? \|", lines[i])
                if not m:
                    break
                row, sup, wall = m.group(1), m.group(2) or "", m.group(3) or ""
                vals = {n: compute(res, starts, row, k) for n, k in cols}
                present = {k: v for k, v in vals.items() if v is not None}
                rank = sorted(present, key=lambda k: present[k]).index("Brood") + 1
                cells = [f"**{fmt_ms(vals[n])}**" if n == "Brood" else fmt_ms(vals[n])
                         for n, _ in cols]
                tail = f" | {rank}/{len(present)} |"
                if rated and not is_codec:
                    tail += f" {rating(present.get('Brood'), min(present.values()))} |"
                out.append(f"| `{row}`{sup}{wall} | " + " | ".join(cells) + tail)
                rows += 1
                i += 1
            continue

        out.append(ln)
        i += 1
    return "\n".join(out), tables, rows


def main():
    check = "--check" in sys.argv
    res, starts = load()
    before = DOC.read_text()
    after, tables, rows = regenerate(before, res, starts)
    if check:
        if before != after:
            print("BENCHMARKS.md is stale — run `python3 bench/tables.py`", file=sys.stderr)
            return 1
        print(f"BENCHMARKS.md up to date ({tables} tables, {rows} rows)")
        return 0
    DOC.write_text(after)
    print(f"BENCHMARKS.md: {tables} tables, {rows} rows, header + overall rating "
          f"{'unchanged' if before == after else 'regenerated'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
