def scoreboard_block(res, starts, specs):
    """The top-of-document scoreboard: every table's normalized score, per language.

    Each table's own top row says the same thing for that table; this is the one place that
    shows all of them together, which is what "how are we doing" actually asks.
    """
    names = [n for n, _ in LANG_COL.items()]
    head = ["| table | " + " | ".join(names) + " |", "|---" * (len(names) + 1) + "|"]
    body = []
    for label, cols, rows in specs:
        row = score_map(res, starts, rows, cols)
        if not row:
            continue
        cells = []
        for n in names:
            v = row.get(n)
            if v is None:
                cells.append("·")
            else:
                txt = f"{v:.2f}"
                cells.append(f"**{txt}**" if n == "Brood" else txt)
        body.append(f"| {label} ({len(rows)}) | " + " | ".join(cells) + " |")
    return [begin("SCOREBOARD"), *head, *body, "",
            "`1.00` = that table's fastest column; each score is the geometric mean of a "
            "language's time ÷ that row's best. `·` = no port in that table. (The colour "
            "bands are on the `vs best` / `vs avg` columns in the tables below: 🟢 at least "
            "as fast · 🟠 up to 3× slower · 🔴 beyond.)",
            end("SCOREBOARD")]


def regenerate(text, res, starts, collect=None, fill=None):
    """Rewrite every generated block and ordered table in one document.

    Two passes, because the SCOREBOARD sits *above* the tables it summarises: pass 1 passes
    `collect=[]` to learn each table's `(label, columns, rows)`, pass 2 passes `fill=specs`
    to emit the board.
    """
    lines = text.split("\n")
    out, i = [], 0
    tables = rows = blocks = 0
    heading = ""
    seen = set()
    while i < len(lines):
        ln = lines[i]

        if ln.startswith("### ") or ln.startswith("**Brood against"):
            heading = re.sub(r"^#+ |\*\*", "", ln).split(" —")[0].split(".")[0].strip()
            heading = re.sub(r"^Brood against (the |its )?", "", heading)

        m = BEGIN_RE.match(ln)
        if m and m.group(1) == "SCOREBOARD":
            if not fill:                           # pass 1: leave it untouched
                out.append(ln)
                i += 1
                while i < len(lines) and not lines[i].startswith(end("SCOREBOARD")):
                    out.append(lines[i])
                    i += 1
                continue
            out += scoreboard_block(res, starts, fill)
            blocks += 1
            while i < len(lines) and not lines[i].startswith(end("SCOREBOARD")):
                i += 1
            i += 1
            continue

        if m and m.group(1) in BLOCKS:
            name = m.group(1)
            out += BLOCKS[name](res, starts)
            blocks += 1
            while i < len(lines) and not lines[i].startswith(end(name)):
                i += 1
            i += 1                      # skip the END marker (emitted by the generator)
            continue

        if ln.startswith("| benchmark |") and "Brood rank" in ln:
            cols = langs_of_header(ln)
            cell_of = dict(header_cells(ln))
            body = []                   # the row names this table covers
            for probe in lines[i + 2:]:
                if probe.startswith("| **score"):
                    continue
                mm = re.match(r"\| `([a-z0-9-]+)`", probe)
                if not mm:
                    break
                body.append(mm.group(1))
            while out and (not out[-1].strip() or out[-1].startswith(SCORE_PREFIX)):
                out.pop()               # the old blockquote score line, if present
            out.append("")
            # The codec table is rated by nothing: its denominators are 2-6 ms of native
            # library time, the ratio its own note tells you not to read.
            is_codec = body[:1] == ["json"]
            rated = not is_codec
            # Columns run fastest -> slowest, which the prose promises and a hand-kept header
            # cannot guarantee: Elixir sat left of Node on the like-for-like table while
            # scoring 1.65 to its 1.62. Ordered by the same score the top row reports.
            sc = score_map(res, starts, body, cols)
            cols = sorted(cols, key=lambda c: sc.get(c[0], float("inf")))
            header = "| benchmark | " + " | ".join(cell_of[n] for n, _ in cols) + " |"
            if rated:
                header += " Brood rank | vs best | vs avg |"
            else:
                header += " Brood rank |"
            header = header.replace("| |", "|")
            out.append(header)
            i += 2                      # header + separator
            out.append("|---" * (len(cols) + 2 + (2 if rated else 0)) + "|")
            if rated:
                label = heading if heading not in seen else f"{heading} (context)"
                seen.add(label)
                if collect is not None:
                    collect.append((label, cols, body))
            if rated:
                sr = score_row(res, starts, body, cols)
                if sr:
                    out.append(sr)
            # Skip the previous run's score row: it is a `|` line the data-row regex below
            # does not match, so leaving it would break out of the row loop and copy every
            # data row through UNREGENERATED — stale numbers, silently. (Caught by the row
            # counter reading 3 instead of 39.)
            if i < len(lines) and lines[i].startswith("| **score"):
                i += 1
            tables += 1
            while i < len(lines) and lines[i].startswith("|"):
                mm = re.match(r"\| `([a-z0-9-]+)`( <sup>[a-z]</sup>)?( \(wall\))? \|",
                              lines[i])
                if not mm:
                    break
                row, sup, wall = mm.group(1), mm.group(2) or "", mm.group(3) or ""
                vals = {n: compute(res, starts, row, k) for n, k in cols}
                present = {k: v for k, v in vals.items() if v is not None}
                rank = sorted(present, key=lambda k: present[k]).index("Brood") + 1
                cells = [f"**{fmt_ms(vals[n])}**" if n == "Brood" else fmt_ms(vals[n])
                         for n, _ in cols]
                tail = f" | {rank}/{len(present)} |"
                if rated:
                    b = present.get("Brood")
                    tail += (f" {rating(b, present)} | {rating_avg(b, present)} |")
                out.append(f"| `{row}`{sup}{wall} | " + " | ".join(cells) + tail)
                rows += 1
                i += 1
            continue

        out.append(ln)
        i += 1
    return "\n".join(out), tables, rows, blocks


def main():
    check = "--check" in sys.argv
    res, starts = load()
    stale, totals = [], [0, 0, 0]
    for doc in DOCS:
        before = doc.read_text()
        specs = []
        regenerate(before, res, starts, collect=specs)       # pass 1: learn the tables
        after, t, r, b = regenerate(before, res, starts, fill=specs)   # pass 2: emit
        totals = [totals[i] + v for i, v in enumerate((t, r, b))]
        if before != after:
            stale.append(doc.name)
            if not check:
                doc.write_text(after)
    what = f"{totals[0]} tables, {totals[1]} rows, {totals[2]} blocks"
    if check:
        if stale:
            print(f"stale, run `python3 bench/docs.py`: {', '.join(stale)}", file=sys.stderr)
            return 1
        print(f"docs up to date ({what})")
        return 0
    print(f"regenerated {what}" + (f" — updated {', '.join(stale)}" if stale
                                   else " — already current"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
