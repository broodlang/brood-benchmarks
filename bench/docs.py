#!/usr/bin/env python3
"""Regenerate every derivable number in BENCHMARKS.md and README.md from results.json.

    python3 bench/docs.py           # rewrite in place
    python3 bench/docs.py --check   # exit 1 if stale (run before committing)

Owns: anything between `<!-- BEGIN NAME -->` / `<!-- END NAME -->` (MACHINE, LATENCY, PEER,
COROUTINE in BENCHMARKS.md; STANDINGS, ENVIRONMENT in README.md), plus every ordered
per-row table — its times, `Brood rank`, `vs best`, `vs avg`, and the score line above it.
Language columns come from each table's own header, so re-ordering one is honoured.

Prose is hand-written. Cite a number in prose only where the argument needs it: a figure
typed into a sentence is stale after the next run, which is why this file exists (on
2026-08-05 a hand-publish left six tables, the run date and the brood commit describing the
previous run).
"""

import re
import sys

from common import COMPUTE, LANG_COL, PRETTY, ROOT, compute, geomean, load

DOCS = [ROOT / "BENCHMARKS.md", ROOT / "README.md"]

BEGIN_RE = re.compile(r"^<!-- BEGIN ([A-Z_]+)(?: \(generated by [^)]*\))? -->")


def begin(name):
    return f"<!-- BEGIN {name} (generated by bench/docs.py) -->"


def end(name):
    return f"<!-- END {name} -->"


def cores(d):
    return (d.get("cpu_pct") or 0) / 100.0


def cpu_s(d):
    return (d["wall_ms"] / 1000.0) * cores(d) if d.get("cpu_pct") else None


def fmt_s(ms):
    return f"{ms / 1000:.2f} s" if ms >= 1000 else f"{round(ms)} ms"


def fmt_gb(kb):
    return f"{kb / 1048576:.2f} GB" if kb >= 1048576 else f"{round(kb / 1024)} MB"


def fmt_ms(v):
    if v is None:
        return "—"
    if v < 1:
        return "&lt;1ms"           # a cell at the startup-subtraction floor
    return f"{round(v)}ms" if v < 1000 else f"{v / 1000:.1f}s"


def rating(brood, best):
    """The `vs best` cell: how far Brood is from the fastest column in that table."""
    if brood is None or best is None or best <= 0:
        return "—"
    return "**best**" if brood <= best else f"{brood / best:.1f}×"


def rating_avg(brood, others):
    """The `vs avg` cell: Brood against the **geometric** mean of the other ports.

    Below 1.0× means Brood beats the field's typical runtime on that row, which is a
    different and often more useful question than the distance to the single fastest — a
    row can be 9× off the best and still ahead of most of the field. See
    `common.geomean` for why the mean is geometric.
    """
    g = geomean(others)
    if brood is None or not g:
        return "—"
    return f"{brood / g:.2f}×" if brood < g else f"{brood / g:.1f}×"


def langs_of_header(header):
    out = []
    for cell in [c.strip() for c in header.strip().strip("|").split("|")][1:]:
        name = re.sub(r"<sup>.*?</sup>", "", cell).strip()
        if name in LANG_COL:
            out.append((name, LANG_COL[name]))
    return out


def machine_line(res):
    m = res["_meta"]
    v = m["versions"]
    date = m["date"].split(" ")[0]
    brood = v["brood"].replace("brood ", "")
    commit = m.get("brood_commit")
    brood = f"{brood} (`{commit}`)" if commit else brood
    elixir = re.sub(r" \(compiled with Erlang/OTP (\d+)\)", r" / OTP \1", v["elixir"])
    elixir = elixir.replace("Elixir ", "").replace(" (", " (")
    return (
        f"Machine: `{m['host']}`, {m['cores']}-core x86-64, "
        f"Linux {m['platform'].split('-')[1]}, **{date}** · Brood {brood} · "
        f"{v['clojure']} · Elixir {elixir} · {v['python']} · Node {v['node']} · "
        f"Ruby {v['ruby'].split(' (')[0].replace('ruby ', '')} · .NET {v['dotnet']}."
    )


def overall_numbers(res, starts):
    """The aggregate / typical-row figures, shared by the BENCHMARKS Overall block and
    README's standings table so the two cannot disagree."""
    langs = [l for l in res["startup"]["langs"] if all(
        compute(res, starts, r, l) is not None for r in COMPUTE)]
    sums = {l: sum(compute(res, starts, r, l) for r in COMPUTE) for l in langs}
    best_sum = min(sums.values())
    order = sorted(sums, key=lambda l: sums[l])
    ratios = []
    for r in COMPUTE:
        vals = [v for v in (compute(res, starts, r, l) for l in langs) if v is not None]
        b = compute(res, starts, r, "brood")
        if b and vals and min(vals) > 0:
            ratios.append(b / min(vals))
    geo = 1.0
    for x in ratios:
        geo *= x
    geo **= 1 / len(ratios)
    wins = sum(1 for x in ratios if x <= 1.0)
    close = sum(1 for x in ratios if 1.0 < x <= 2.0)
    # Against the field's typical runtime rather than its fastest: the geometric mean of
    # the other ports' aggregates, and how many rows Brood is ahead of that mean on.
    field_geo = geomean([sums[l] for l in langs if l != "brood"])
    avg_ratios = []
    for r in COMPUTE:
        b = compute(res, starts, r, "brood")
        g = geomean([compute(res, starts, r, l) for l in langs if l != "brood"])
        if b and g:
            avg_ratios.append(b / g)
    return {
        "agg_avg": sums["brood"] / field_geo if field_geo else None,
        "beats_avg": sum(1 for x in avg_ratios if x < 1.0),
        "navg": len(avg_ratios),
        "langs": langs, "nlangs": len(langs), "nrows": len(ratios),
        "agg": sums["brood"] / best_sum, "rank": order.index("brood") + 1,
        "geo": geo, "med": sorted(ratios)[len(ratios) // 2],
        "wins": wins, "within2": wins + close,
        "mid": sum(1 for x in ratios if 2.0 < x <= 5.0),
        "far": sum(1 for x in ratios if x > 5.0),
        "worst_row": COMPUTE[max(range(len(ratios)), key=lambda i: ratios[i])],
        "worst": max(ratios),
        "field": [(l, sums[l] / best_sum) for l in order if l != "brood"],
    }


SCORE_PREFIX = "> **Score** —"


def table_score(res, starts, rows, cols):
    """One line per table: Brood's typical distance to the best and to the field average
    over that table's rows, plus its rank.

    Rank is by each language's own geometric mean of per-row `x / row_best`, not by summed
    ms: a sum is dominated by the largest absolute rows, which put Brood 1st here purely
    because it beats .NET by 600 ms on `errors-deep`.
    """
    names = [n for n, _ in cols]
    keys = dict(cols)
    best_r, avg_r, wins = [], [], 0
    per_lang = {n: [] for n in names}
    for row in rows:
        vals = {n: compute(res, starts, row, keys[n]) for n in names}
        vals = {n: v for n, v in vals.items() if v is not None}
        if "Brood" not in vals or len(vals) < 2:
            continue
        b, lo = vals["Brood"], min(vals.values())
        best_r.append(b / lo if lo else 1.0)
        wins += b <= lo
        g = geomean([v for n, v in vals.items() if n != "Brood"])
        if g:
            avg_r.append(b / g)
        for n, v in vals.items():
            if lo:
                per_lang[n].append(v / lo)
    if not best_r:
        return None
    scored = {n: geomean(r) for n, r in per_lang.items() if r}
    rank = sorted(scored, key=lambda n: scored[n]).index("Brood") + 1
    tail = f" · fastest on {wins}" if wins else ""
    return (f"{SCORE_PREFIX} Brood over these {len(best_r)} rows: {geomean(best_r):.1f}× best · "
            f"{geomean(avg_r):.2f}× avg · rank {rank}/{len(scored)}{tail}")


def latency_block(res, starts):
    """The open-loop percentile table, ordered by p99 and rated against the best p99."""
    langs = [(PRETTY[l], l) for l in res["latency"]["langs"]
             if res["latency"]["langs"][l].get("metrics")]
    def m(l, k):
        return res["latency"]["langs"][l]["metrics"][k]
    langs.sort(key=lambda p: m(p[1], "p99_us"))
    best = m(langs[0][1], "p99_us")
    rows = [begin("LATENCY"),
            "| | p50 | **p99** | p99.9 | max | cores | CPU·s | peak RSS | vs best (p99) |",
            "|---|---|---|---|---|---|---|---|---|"]
    for nice, l in langs:
        d = res["latency"]["langs"][l]
        p99 = m(l, "p99_us")
        rate = "**best**" if p99 <= best else f"{p99 / best:.1f}×"
        rows.append(
            f"| **{nice}** | {m(l,'p50_us'):,} µs | **{p99:,} µs** | "
            f"{m(l,'p999_us'):,} µs | {m(l,'max_us'):,} µs | {cores(d):.1f}× | {cpu_s(d):.2f} | "
            f"{round(d['rss_kb']/1024)} MB | {rate} |")
    rows.append(end("LATENCY"))
    return rows


def spawn_live_table(res, starts, langs, label, name):
    """`spawn-live` for a subset of the field — the peer table and the coroutine table."""
    got = [(PRETTY[l], l) for l in langs if res["spawn-live"]["langs"].get(l)]
    got.sort(key=lambda p: compute(res, starts, "spawn-live", p[1]))
    best = min(compute(res, starts, "spawn-live", l) for _, l in got)
    rows = [begin(name), f"| | compute | peak RSS | cores | CPU·s | vs best |",
            "|---|---|---|---|---|---|"]
    for nice, l in got:
        d = res["spawn-live"]["langs"][l]
        c = compute(res, starts, "spawn-live", l)
        rows.append(f"| **{nice}** ({label[l]}) | {fmt_s(c)} | {fmt_gb(d['rss_kb'])} | "
                    f"{cores(d):.1f}× | {cpu_s(d):.2f} | "
                    f"{'**best**' if c <= best else f'{c / best:.1f}×'} |")
    rows.append(end(name))
    return rows


def peer_block(res, starts):
    return spawn_live_table(res, starts, ["elixir", "brood"],
                            {"elixir": "BEAM process", "brood": "green process"}, "PEER")


def coroutine_block(res, starts):
    return spawn_live_table(res, starts, ["node", "dotnet", "python"],
                            {"node": "promise", "dotnet": "`Task`",
                             "python": "`asyncio` task"}, "COROUTINE")


def standings_block(res, starts):
    """README's summary table: where Brood lands, and against whom."""
    o = overall_numbers(res, starts)
    def field(row, key, unit, scale=1.0, prec=1):
        vals = []
        for l, d in res[row]["langs"].items():
            if l == "brood" or d.get(key) is None:
                continue
            vals.append((PRETTY[l], d[key] * scale))
        vals.sort(key=lambda p: p[1])
        return ", ".join(f"{n} {v:.{prec}f}" for n, v in vals) + unit
    firsts, lasts = [], []
    for row in res:
        # `startup` has no compute, and a percentile row (`latency`) is ranked by p99 — its
        # wall is N/rate by construction, so a compute rank there is not a fact about speed.
        if row.startswith("_") or row == "startup" or res[row]["langs"].get(
                "brood", {}).get("metrics"):
            continue
        ls = [l for l in res[row]["langs"] if compute(res, starts, row, l) is not None]
        if "brood" not in ls or len(ls) < 3:
            continue
        order = sorted(ls, key=lambda l: compute(res, starts, row, l))
        if order[0] == "brood":
            firsts.append(f"`{row}`")
        if order[-1] == "brood":
            lasts.append(f"`{row}`")
    sl, sup, lat = (res["spawn-live"]["langs"], res["supervisor"]["langs"],
                    res["latency"]["langs"])
    def lm(l, k):
        return lat[l]["metrics"][k]
    others = " · ".join(f"{PRETTY[l]} {lm(l,'p99_us')} / {lm(l,'p999_us')} µs"
                        for l in sorted((x for x in lat if x != "brood" and lat[x].get("metrics")),
                                        key=lambda x: lm(x, "p99_us")))
    return [
        begin("STANDINGS"),
        f"**{res['_meta']['date'].split(' ')[0]} run.** Numbers regenerate with each run; "
        "the full table is in [BENCHMARKS.md](BENCHMARKS.md).",
        "",
        "| | Brood | field |",
        "|---|---|---|",
        f"| startup (wall) | {res['startup']['langs']['brood']['wall_ms']:.1f} ms | "
        f"{field('startup', 'wall_ms', ' ms')} |",
        f"| base RSS | {res['startup']['langs']['brood']['rss_kb']/1024:.1f} MB | "
        f"{field('startup', 'rss_kb', ' MB', 1/1024)} |",
        f"| aggregate single-threaded compute | {o['agg']:.1f}× the fastest | "
        + " · ".join(f"{PRETTY[l]} {v:.1f}" for l, v in o["field"]) + " |",
        f"| aggregate vs the field's average | **{o['agg_avg']:.2f}×** | "
        f"ahead of the field average on {o['beats_avg']} of {o['navg']} core-compute rows |",
        f"| rank by row | 1st on {', '.join(firsts) or '—'}; "
        f"last on {', '.join(lasts) or '—'} | |",
        f"| `spawn-live` (300k units held alive, each sent a copied message) | "
        f"{fmt_s(compute(res, starts, 'spawn-live', 'brood'))}, "
        f"{fmt_gb(sl['brood']['rss_kb'])}, {cpu_s(sl['brood']):.2f} CPU·s | "
        f"Elixir {fmt_s(compute(res, starts, 'spawn-live', 'elixir'))} / "
        f"{fmt_gb(sl['elixir']['rss_kb'])} — the only peer; "
        + ", ".join(f"{PRETTY[l]} {fmt_s(compute(res, starts, 'spawn-live', l))} / "
                    f"{fmt_gb(sl[l]['rss_kb'])}" for l in ("node", "dotnet", "python")
                    if l in sl)
        + " are coroutines on a shared heap |",
        f"| `supervisor` (20k supervised children, a quarter retired and restarted) | "
        f"{fmt_s(compute(res, starts, 'supervisor', 'brood'))}, "
        f"{fmt_gb(sup['brood']['rss_kb'])} | "
        f"Elixir {fmt_s(compute(res, starts, 'supervisor', 'elixir'))} / "
        f"{fmt_gb(sup['elixir']['rss_kb'])} — the only peer; no other runtime here has a "
        "supervisor |",
        f"| `latency` p99 / p99.9 (20k req/s, 5% of them occupying 500µs) | "
        f"**{lm('brood','p99_us')} µs / {lm('brood','p999_us')} µs** | {others} — the "
        "compute winner has the worst tail |",
        end("STANDINGS"),
    ]


def environment_block(res, starts):
    m, v = res["_meta"], res["_meta"]["versions"]
    commit = f" (`{m['brood_commit']}`)" if m.get("brood_commit") else ""
    return [
        begin("ENVIRONMENT"),
        f"Numbers in the docs were measured on `{m['host']}`: a {m['cores']}-core x86-64 "
        f"Linux {m['platform'].split('-')[1]} machine · Brood "
        f"{v['brood'].replace('brood ', '')}{commit} (bytecode VM + tier-1 JIT) · "
        f"{v['clojure'].replace(' / JDK', ' / OpenJDK')} (HotSpot) · "
        f"{re.sub(r' \(compiled with Erlang/OTP (\d+)\)', r' / OTP \1', v['elixir'])} "
        f"(BeamAsm JIT) · {v['python']} · Node {v['node'].lstrip('v')} (V8) · "
        f"{v['ruby'].split(' (')[0]} · .NET {v['dotnet']} (RyuJIT). "
        f"{m['date'].split(' ')[0]}.",
        end("ENVIRONMENT"),
    ]


BLOCKS = {
    "MACHINE": lambda res, starts: [begin("MACHINE"), machine_line(res), end("MACHINE")],
    "LATENCY": latency_block,
    "PEER": peer_block,
    "COROUTINE": coroutine_block,
    "STANDINGS": standings_block,
    "ENVIRONMENT": environment_block,
}


def regenerate(text, res, starts):
    """Rewrite every generated block and ordered table in one document."""
    lines = text.split("\n")
    out, i = [], 0
    tables = rows = blocks = 0
    while i < len(lines):
        ln = lines[i]

        m = BEGIN_RE.match(ln)
        if m and m.group(1) in BLOCKS:
            name = m.group(1)
            out += BLOCKS[name](res, starts)
            blocks += 1
            while i < len(lines) and not lines[i].startswith(end(name)):
                i += 1
            i += 1                      # skip the END marker (emitted by the generator)
            continue

        if ln.startswith("| benchmark |") and "Brood rank" in ln:
            cols = langs_of_header(ln)
            body = []                   # the row names this table covers
            for probe in lines[i + 2:]:
                mm = re.match(r"\| `([a-z0-9-]+)`", probe)
                if not mm:
                    break
                body.append(mm.group(1))
            # Strip whatever precedes the table (a previous score line, blank lines) and
            # re-emit exactly one separator + score + separator, so a rewrite is a fixed
            # point — `--check` compares text, and one stray blank per run would make the
            # doc permanently "stale".
            while out and (not out[-1].strip() or out[-1].startswith(SCORE_PREFIX)):
                out.pop()
            # The codec table is rated by nothing: its denominators are 2-6 ms of native
            # library time, the ratio its own note tells you not to read.
            is_codec = body[:1] == ["json"]
            rated = not is_codec
            score = None if is_codec else table_score(res, starts, body, cols)
            out += ["", score, ""] if score else [""]
            header = ln
            if not is_codec:
                header = re.sub(r"\| Brood rank \|.*$", "| Brood rank | vs best | vs avg |",
                                ln)
            out.append(header)
            i += 2                      # header + separator
            out.append("|---" * (len(cols) + 2 + (2 if rated else 0)) + "|")
            tables += 1
            while i < len(lines) and lines[i].startswith("|"):
                mm = re.match(r"\| `([a-z0-9-]+)`( <sup>[a-z]</sup>)?( \(wall\))? \|",
                              lines[i])
                if not mm:
                    break
                row, sup, wall = mm.group(1), mm.group(2) or "", mm.group(3) or ""
                vals = {n: compute(res, starts, row, k) for n, k in cols}
                present = {k: v for k, v in vals.items() if v is not None}
                rank = sorted(present, key=lambda k: present[k]).index("Brood") + 1
                cells = [f"**{fmt_ms(vals[n])}**" if n == "Brood" else fmt_ms(vals[n])
                         for n, _ in cols]
                tail = f" | {rank}/{len(present)} |"
                if rated:
                    others = [v for k, v in present.items() if k != "Brood"]
                    tail += (f" {rating(present.get('Brood'), min(present.values()))} |"
                             f" {rating_avg(present.get('Brood'), others)} |")
                out.append(f"| `{row}`{sup}{wall} | " + " | ".join(cells) + tail)
                rows += 1
                i += 1
            continue

        out.append(ln)
        i += 1
    return "\n".join(out), tables, rows, blocks


def main():
    check = "--check" in sys.argv
    res, starts = load()
    stale, totals = [], [0, 0, 0]
    for doc in DOCS:
        before = doc.read_text()
        after, t, r, b = regenerate(before, res, starts)
        totals = [totals[0] + t, totals[1] + r, totals[2] + b]
        if before != after:
            stale.append(doc.name)
            if not check:
                doc.write_text(after)
    what = f"{totals[0]} tables, {totals[1]} rows, {totals[2]} blocks"
    if check:
        if stale:
            print(f"stale, run `python3 bench/docs.py`: {', '.join(stale)}", file=sys.stderr)
            return 1
        print(f"docs up to date ({what})")
        return 0
    print(f"regenerated {what}" + (f" — updated {', '.join(stale)}" if stale
                                   else " — already current"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
